-- Apply only to the NEW dedicated Raffli Portfolio CMS Supabase project.
-- Administrator must be created in Auth then inserted into portfolio_admins using their auth.users UUID.
create table if not exists public.portfolio_admins (
 id uuid primary key references auth.users(id) on delete cascade
);
alter table public.portfolio_admins enable row level security;
revoke all on public.portfolio_admins from anon,authenticated;
grant select on public.portfolio_admins to authenticated;
create policy "Admin can inspect own record" on public.portfolio_admins
 for select to authenticated using (id=(select auth.uid()));
create table if not exists public.portfolio_projects (
 id bigint generated by default as identity (start with 1000) primary key,
 slug text unique not null check (char_length(slug) between 1 and 120),
 status text not null default 'draft' check(status in ('draft','published','archived')),
 data jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.portfolio_projects enable row level security;
grant select on public.portfolio_projects to anon, authenticated;
grant insert,update,delete on public.portfolio_projects to authenticated;
create policy "Published projects are public" on public.portfolio_projects
 for select to anon, authenticated using (status='published');
create policy "Admins read all projects" on public.portfolio_projects
 for select to authenticated using (exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid())));
create policy "Admins insert projects" on public.portfolio_projects
 for insert to authenticated with check (exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid())));
create policy "Admins update projects" on public.portfolio_projects
 for update to authenticated using (exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid())))
 with check (exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid())));
create policy "Admins delete projects" on public.portfolio_projects
 for delete to authenticated using (exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid())));
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
 values ('portfolio-images','portfolio-images',true,6291456,array['image/jpeg','image/png','image/webp','image/avif'])
 on conflict (id) do nothing;
create policy "Admins upload portfolio images" on storage.objects
 for insert to authenticated with check (
 bucket_id='portfolio-images' and
 (storage.foldername(name))[1]=(select auth.uid())::text and
 exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid()))
);
create policy "Admins delete own portfolio images" on storage.objects
 for delete to authenticated using (
 bucket_id='portfolio-images' and
 (storage.foldername(name))[1]=(select auth.uid())::text and
 exists(select 1 from public.portfolio_admins a where a.id=(select auth.uid()))
);
